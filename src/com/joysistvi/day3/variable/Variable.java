package com.joysistvi.day3.variable;

public class Variable {
    public static void main(String[] args) {
        //initialize a variable
        byte age = 69;
        System.out.println(age);
        short num = 129;
        System.out.println(num);
        int num2 = 12900;
        System.out.println(num2);
        long num3 = 1290000000000L;
        System.out.println(num3);

        float average = 99.000f;
        System.out.println(average);
        double price = 10.5;
        System.out.println(price);

        boolean is_active = true;
        System.out.println(is_active);

        char middleInitial = 'L';
        String firstName = "James Michael";
        String lastName = "Solamo";
        System.out.println("Full Name: "+lastName+ ", " + firstName + " " + middleInitial +".");
    }
}

